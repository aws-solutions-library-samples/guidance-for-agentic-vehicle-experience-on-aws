def _is_tool_decorator(node: ast.expr) -> bool:
    """True if the decorator node resolves to the Strands ``@tool`` decorator.

    Matches:
        @tool                       → ast.Name id='tool'
        @strands.tool / @mod.tool   → ast.Attribute attr='tool'
        @tool(name="x")             → ast.Call whose .func is either above
    """
    if isinstance(node, ast.Name):
        return node.id == "tool"
    if isinstance(node, ast.Attribute):
        return node.attr == "tool"
    if isinstance(node, ast.Call):
        return _is_tool_decorator(node.func)
    return False


def _parse_all_list(init_tree: ast.Module) -> list[str]:
    """Extract ``__all__`` list from the tools/__init__.py AST.

    Returns factory names only (items starting with ``make_``).
    ``PERSONA_TOOL_FACTORIES`` and other non-factory exports are excluded.
    """
    for node in ast.walk(init_tree):
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == "__all__":
                    if isinstance(node.value, ast.List):
                        return [
                            e.value
                            for e in node.value.elts
                            if isinstance(e, ast.Constant)
                            and isinstance(e.value, str)
                            and e.value.startswith("make_")
                        ]
    return []


def _parse_persona_tool_factories(init_tree: ast.Module) -> dict[str, list[str]]:
    """Extract ``PERSONA_TOOL_FACTORIES`` dict from the tools/__init__.py AST.

    Returns {persona_name: [factory_name, ...]} in declaration order.
    Uses AnnAssign (the source has a type annotation: ``dict[str, list]``).
    """
    for node in ast.walk(init_tree):
        if isinstance(node, ast.AnnAssign):
            if (
                isinstance(node.target, ast.Name)
                and node.target.id == "PERSONA_TOOL_FACTORIES"
                and isinstance(node.value, ast.Dict)
            ):
                result: dict[str, list[str]] = {}
                for k, v in zip(node.value.keys, node.value.values):
                    if not isinstance(k, ast.Constant) or not isinstance(k.value, str):
                        continue
                    persona = k.value
                    if not isinstance(v, ast.List):
                        continue
                    factories = [
                        e.id
                        for e in v.elts
                        if isinstance(e, ast.Name) and e.id.startswith("make_")
                    ]
                    result[persona] = factories
                return result
    return {}


def _parse_kiosk_tool_factories(supervisor_tree: ast.Module) -> list[str]:
    """Extract ``_KIOSK_TOOL_FACTORIES`` list of string literals from supervisor.py."""
    for node in ast.walk(supervisor_tree):
        if isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name) and t.id == "_KIOSK_TOOL_FACTORIES":
                    if isinstance(node.value, ast.List):
                        return [
                            e.value
                            for e in node.value.elts
                            if isinstance(e, ast.Constant)
                            and isinstance(e.value, str)
                        ]
    return []


def _extract_first_sentence(doc: str) -> str:
    """Extract the first sentence from a docstring.

    Algorithm (spec D5, amended 2026-08-03):
    1. Take the first paragraph — everything up to the first blank line.
    2. Collapse all internal whitespace (newlines, multiple spaces) to single spaces.
    3. Cut at the first sentence terminator (. ! ?), retaining it.
    4. If no terminator is found, width-truncate at a word boundary with an ellipsis.
    """
    if not doc:
        return ""

    # Step 1: take first paragraph (up to first blank line)
    paragraphs = doc.split("\n\n")
    first_para = paragraphs[0].strip()

    # Step 2: collapse internal whitespace to single spaces
    collapsed = " ".join(first_para.split())

    # Step 3: cut at first sentence terminator (., !, ?)
    for i, ch in enumerate(collapsed):
        if ch in ".!?":
            return collapsed[: i + 1]

    # Step 4: no terminator found — width-truncate at word boundary with ellipsis
    return textwrap.shorten(collapsed, width=120, placeholder="…")


def _parse_tool_functions(
    tool_file: Path,
) -> tuple[list[str], dict[str, list[ToolEntry]]]:
    """Parse a single tools/<mod>.py file.

    Returns:
        (defined_factories, tools_by_factory)
        defined_factories -- list of ``make_*_tool`` names at module level
        tools_by_factory  -- {factory_name: [(tool_name, description), ...]}
    """
    src = tool_file.read_text(encoding="utf-8")
    tree = ast.parse(src)

    defined_factories: list[str] = []
    tools_by_factory: dict[str, list[ToolEntry]] = {}

    for node in ast.iter_child_nodes(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        if not (node.name.startswith("make_") and node.name.endswith("_tool")):
            continue

        defined_factories.append(node.name)
        entries: list[ToolEntry] = []

        # Walk into the factory to find nested @tool-decorated functions.
        for inner in ast.walk(node):
            if inner is node:
                continue
            if not isinstance(inner, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            # Must have a @tool decorator.
            if not any(_is_tool_decorator(dec) for dec in inner.decorator_list):
                continue
            doc = ast.get_docstring(inner)
            # Spec D5 (amended 2026-08-03): first sentence of first paragraph,
            # not first line — three docstrings wrap their opening sentence.
            description = _extract_first_sentence(doc or "")
            entries.append(ToolEntry(name=inner.name, description=description))

        tools_by_factory[node.name] = entries

    return defined_factories, tools_by_factory



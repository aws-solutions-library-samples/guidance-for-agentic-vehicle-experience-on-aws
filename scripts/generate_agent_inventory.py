def build_inventory(repo_root: Path) -> Inventory:
    """Parse all relevant source files and return a complete Inventory.

    Validates classification invariants and raises SystemExit with an
    explicit message for any hard error (orphan export, unregistered
    factory, undocumented tool).

    No agent module is imported — pure AST analysis.
    """
    tools_dir = repo_root / _TOOLS_DIR_REL
    supervisor_path = repo_root / _SUPERVISOR_REL
    init_path = repo_root / _INIT_REL

    # --- Parse source files --------------------------------------------------

    init_src = init_path.read_text(encoding="utf-8")
    init_tree = ast.parse(init_src)

    supervisor_src = supervisor_path.read_text(encoding="utf-8")
    supervisor_tree = ast.parse(supervisor_src)

    # --- Extract registry data -----------------------------------------------

    exported = _parse_all_list(init_tree)
    persona_factories = _parse_persona_tool_factories(init_tree)
    kiosk_factories = _parse_kiosk_tool_factories(supervisor_tree)

    # --- Parse every tool module (excl. __init__.py) -------------------------

    all_defined: list[str] = []
    tools_by_factory: dict[str, list[ToolEntry]] = {}
    factory_to_module: dict[str, str] = {}

    tool_modules = sorted(
        [f for f in tools_dir.glob("*.py") if f.name != "__init__.py"]
    )
    for tool_file in tool_modules:
        module_name = tool_file.stem
        defined, tbl = _parse_tool_functions(tool_file)
        all_defined.extend(defined)
        tools_by_factory.update(tbl)
        for fname in defined:
            factory_to_module[fname] = module_name

    # --- Build surfaces -------------------------------------------------------

    surfaces: dict[str, list[str]] = {}
    for persona, factories in persona_factories.items():
        surfaces[persona] = list(factories)  # preserve declaration order
    surfaces["kiosk"] = list(kiosk_factories)

    # --- Validate: orphan exports ---------------------------------------------

    surfaced: set[str] = set()
    for flist in surfaces.values():
        surfaced.update(flist)

    orphans = [f for f in exported if f not in surfaced]
    if orphans:
        _hard_error(
            f"Orphan export(s) detected — in __all__ but in no surface: "
            + ", ".join(orphans)
        )

    # --- Validate: surface ↔ export symmetry ---------------------------------
    # Every factory referenced by any surface must appear in __all__.
    # If it doesn't, the inventory silently undercounts (the summary table
    # iterates ``exported``) — which is exactly the failure mode the drift gate
    # is meant to make impossible.  Spec: T3.0 symmetry hard-error.

    exported_set = set(exported)
    not_exported: list[tuple[str, str]] = []  # [(factory, surface_name), ...]
    for surface_name, factory_list in surfaces.items():
        for factory_name in factory_list:
            if (
                factory_name not in exported_set
                and factory_name not in INTERNAL_HELPER_FACTORIES
            ):
                not_exported.append((factory_name, surface_name))

    if not_exported:
        by_factory: dict[str, list[str]] = {}
        for factory_name, surface_name in not_exported:
            by_factory.setdefault(factory_name, []).append(surface_name)
        details = "; ".join(
            f"'{f}' referenced in surfaces {surfaces_list}"
            for f, surfaces_list in by_factory.items()
        )
        _hard_error(
            "Surface factory/factories not in __all__ — inventory would silently "
            "undercount.  Add each to __all__ or INTERNAL_HELPER_FACTORIES: "
            + details
        )

    # --- Validate: unregistered factories ------------------------------------

    unregistered = [
        f
        for f in all_defined
        if f not in exported and f not in INTERNAL_HELPER_FACTORIES
    ]
    if unregistered:
        _hard_error(
            "Unregistered factory/factories detected (defined but not exported "
            "and not in INTERNAL_HELPER_FACTORIES): " + ", ".join(unregistered)
        )

    # --- Validate: undocumented tools ----------------------------------------

    for factory_name in exported:
        entries = tools_by_factory.get(factory_name, [])
        if not entries:
            _hard_error(
                f"Registered factory '{factory_name}' has no @tool function. "
                "Add a @tool-decorated inner function."
            )
        for tool_name, description in entries:
            if not description.strip():
                _hard_error(
                    f"Registered factory '{factory_name}' / tool '{tool_name}' "
                    "has an empty or missing docstring first line. "
                    "Add a descriptive docstring to the @tool function."
                )

    return Inventory(
        exported=exported,
        all_defined=all_defined,
        surfaces=surfaces,
        tools_by_factory=tools_by_factory,
        factory_to_module=factory_to_module,
    )


def _hard_error(msg: str) -> None:
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)



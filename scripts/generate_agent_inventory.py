def render_readme_region(inv: Inventory) -> str:
    """Render the content that belongs between the README markers (not including them).

    The returned string starts with a newline so the marker and content
    are on separate lines, and ends with a newline before the end marker.
    """
    lines: list[str] = []
    lines.append("")
    lines.append(
        f"> **{len(inv.exported)} registered LLM-visible tools across "
        f"{len(inv.surfaces)} surfaces** "
        f"(+ {len(INTERNAL_HELPER_FACTORIES)} internal composition helper)."
    )
    lines.append(
        "> See [`docs/AGENT-INVENTORY.md`](docs/AGENT-INVENTORY.md) for the full table."
    )
    lines.append(">")
    lines.append("> | Surface | Tool count |")
    lines.append("> |---------|------------|")
    for surface_key, factory_list in inv.surfaces.items():
        label = _SURFACE_LABELS.get(surface_key, surface_key)
        lines.append(f"> | {label} | {len(factory_list)} |")
    lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# README rewriter
# ---------------------------------------------------------------------------


def _rewrite_readme(readme_path: Path, inv: Inventory) -> str:
    """Rewrite the README fenced region in-place. Returns the new content."""
    text = readme_path.read_text(encoding="utf-8")

    if README_BEGIN_MARKER not in text:
        _hard_error(
            f"Missing begin marker in README.md: {README_BEGIN_MARKER!r}\n"
            "Add the marker pair to README.md before running the generator."
        )
    if README_END_MARKER not in text:
        _hard_error(
            f"Missing end marker in README.md: {README_END_MARKER!r}\n"
            "Add the marker pair to README.md before running the generator."
        )

    region = render_readme_region(inv)
    start = text.index(README_BEGIN_MARKER) + len(README_BEGIN_MARKER)
    end = text.index(README_END_MARKER)
    new_text = text[:start] + region + text[end:]
    return new_text


# ---------------------------------------------------------------------------
# --check mode: diff on-disk vs freshly generated
# ---------------------------------------------------------------------------


def _check_artifact(
    path: Path, fresh_content: str, label: str
) -> list[str]:
    """Return unified-diff lines if content differs, else []."""
    if not path.exists():
        return [
            f"--- {label} (on-disk)\n",
            f"+++ {label} (generated)\n",
            f"@@ -0,0 +1,{len(fresh_content.splitlines())} @@\n",
        ] + [f"+{line}\n" for line in fresh_content.splitlines()]

    on_disk = path.read_text(encoding="utf-8")
    if on_disk == fresh_content:
        return []

    return list(
        difflib.unified_diff(
            on_disk.splitlines(keepends=True),
            fresh_content.splitlines(keepends=True),
            fromfile=f"{label} (on-disk)",
            tofile=f"{label} (generated)",
        )
    )



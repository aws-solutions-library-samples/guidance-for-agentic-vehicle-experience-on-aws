_HEADER_COMMENT = "<!-- DO NOT EDIT — generated by scripts/generate_agent_inventory.py -->"
_HEADER_ADOC = "// DO NOT EDIT — generated by scripts/generate_agent_inventory.py"
_SURFACE_LABELS = {
    "fleet_driver": "Fleet Driver",
    "consumer": "Consumer",
    "retail_advisor": "Retail Advisor",
    "vehicle_owner": "Vehicle Owner",
    "service_advisor": "Service Advisor",
    "technician": "Technician",
    "kiosk": "Anonymous Kiosk (default-deny allow-list)",
}


def render_markdown(inv: Inventory) -> str:
    """Render the full AGENT-INVENTORY.md content."""
    lines: list[str] = []
    lines.append(_HEADER_COMMENT)
    lines.append("")
    lines.append("# Agent Tool Inventory")
    lines.append("")
    lines.append(
        f"**{len(inv.exported)} registered tools across {len(inv.surfaces)} surfaces.**  "
    )
    lines.append(
        f"**{len(INTERNAL_HELPER_FACTORIES)} internal helper** "
        f"({', '.join(INTERNAL_HELPER_FACTORIES.keys())})."
    )
    lines.append("")
    lines.append(
        "_Source of truth: `agents/supervisor/tools/__init__.py` and "
        "`agents/supervisor/supervisor.py`. "
        "Run `python3 scripts/generate_agent_inventory.py` to regenerate._"
    )
    lines.append("")

    # --- Summary table -------------------------------------------------------
    lines.append("## All Registered Tools")
    lines.append("")
    lines.append("| Tool | Factory | Module | Surfaces | Description |")
    lines.append("|------|---------|--------|----------|-------------|")

    for factory in inv.exported:
        module = inv.factory_to_module.get(factory, "?")
        entries = inv.tools_by_factory.get(factory, [])
        for tool_name, description in entries:
            # Which surfaces list this factory?
            surface_list = [
                _SURFACE_LABELS.get(s, s)
                for s, flist in inv.surfaces.items()
                if factory in flist
            ]
            surfaces_str = ", ".join(surface_list) if surface_list else "—"
            desc_short = textwrap.shorten(description, width=120, placeholder="…")
            lines.append(
                f"| `{tool_name}` | `{factory}` | `{module}` "
                f"| {surfaces_str} | {desc_short} |"
            )

    lines.append("")

    # --- Internal helpers ----------------------------------------------------
    lines.append("## Internal Helpers (not persona-registered)")
    lines.append("")
    for helper, rationale in INTERNAL_HELPER_FACTORIES.items():
        module = inv.factory_to_module.get(helper, "?")
        lines.append(f"- **`{helper}`** (`{module}.py`) — {rationale}")
    lines.append("")

    # --- Per-surface ordered lists -------------------------------------------
    lines.append("## Tools by Surface")
    lines.append("")

    for surface_key, factory_list in inv.surfaces.items():
        label = _SURFACE_LABELS.get(surface_key, surface_key)
        lines.append(f"### {label}")
        lines.append("")
        if not factory_list:
            lines.append("_(none)_")
        else:
            for factory in factory_list:
                entries = inv.tools_by_factory.get(factory, [])
                for tool_name, description in entries:
                    desc_short = textwrap.shorten(description, width=120, placeholder="…")
                    lines.append(f"- **`{tool_name}`** — {desc_short}")
        lines.append("")

    return "\n".join(lines)



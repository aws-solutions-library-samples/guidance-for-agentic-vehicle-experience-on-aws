# ---------------------------------------------------------------------------

README_BEGIN_MARKER = "<!-- BEGIN GENERATED: agent-inventory-summary -->"
README_END_MARKER = "<!-- END GENERATED: agent-inventory-summary -->"

# Internal helpers: factory name → rationale string.
# These are defined under tools/ but are never persona-registered.
# (spec D4 + D5 — seeded value; extend here when new helpers are introduced)
INTERNAL_HELPER_FACTORIES: dict[str, str] = {
    "make_sub_agent_tool": (
        "composition helper wrapped by diy_repair_advisor.py; never persona-registered"
    ),
}

# ---------------------------------------------------------------------------
# Parse targets
# ---------------------------------------------------------------------------

_TOOLS_DIR_REL = Path("agents/supervisor/tools")
_SUPERVISOR_REL = Path("agents/supervisor/supervisor.py")
_INIT_REL = _TOOLS_DIR_REL / "__init__.py"

# ---------------------------------------------------------------------------
# Data shapes — the public ``Inventory`` type the tests pin
# ---------------------------------------------------------------------------


class ToolEntry(NamedTuple):
    """One LLM-visible tool produced by a factory."""
    name: str           # inner @tool function name
    description: str    # first line of the @tool function's docstring


@dataclass
class Inventory:
    """Complete picture of the tool registry.

    Public fields used by tests:
        exported       -- factory names in ``__all__`` (excluding non-factories)
        all_defined    -- every ``make_*_tool`` name found under tools/
        surfaces       -- {surface_name: [factory_name, ...]} in declaration order
        tools_by_factory -- {factory_name: [(tool_name, description), ...]}
    """
    exported: list[str] = field(default_factory=list)
    all_defined: list[str] = field(default_factory=list)
    # surfaces key order: 6 persona names then "kiosk"
    surfaces: dict[str, list[str]] = field(default_factory=dict)
    tools_by_factory: dict[str, list[ToolEntry]] = field(default_factory=dict)

    # Derived convenience — not used by tests but used by renderers
    factory_to_module: dict[str, str] = field(default_factory=dict)



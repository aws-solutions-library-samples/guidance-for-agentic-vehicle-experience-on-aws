"""Generate the CVX agent tool inventory from AST analysis.

DO NOT EDIT — generated by scripts/generate_agent_inventory.py
(This header applies to the OUTPUT artifacts, not this script itself.)

Usage:
    python3 scripts/generate_agent_inventory.py            # write artifacts
    python3 scripts/generate_agent_inventory.py --check    # exit 1 + diff on drift

The generator parses Python source with stdlib ``ast`` — it never imports any
agent module.  Zero non-stdlib dependencies.

Spec: .kiro/specs/2026-08-03-cvx-tier2-doctrine-and-inventory/spec.md § "Generator"
"""

#!/usr/bin/env bash
# measure_tier2_bundle.sh — pre-flight Lambda bundle-size measurement for the
# Tier 2 health agent. Installs only the DEPENDENCY WALL (not the full app
# path) and reports zip + unzipped size.
#
# Usage:
#   bash deployment/scripts/measure_tier2_bundle.sh
#
# Exit codes:
#   0 — measurement complete; size < 200 MB unzipped (R1 gate CLEAR)
#   1 — measurement complete; size >= 200 MB unzipped (R1 gate FIRES)
#   2 — prerequisite error (Docker not available, pip failure, etc.)
#
# Per spec.md § R1: if exit code 1, do NOT proceed to Group 2 — evaluate
# Lambda layers or Fargate before re-opening the gate.
#
# Constraint: dependency wall only, NOT the full application code path.
# This script measures what pip installs, not what the agent does.

set -euo pipefail

# ── Colour helpers ────────────────────────────────────────────────────────────
RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
BOLD='\033[1m'; RESET='\033[0m'
log()  { echo -e "${BOLD}[measure_tier2_bundle]${RESET} $*"; }
ok()   { echo -e "${GREEN}[OK]${RESET} $*"; }
warn() { echo -e "${YELLOW}[WARN]${RESET} $*"; }
err()  { echo -e "${RED}[ERROR]${RESET} $*" >&2; }

# ── Locate repo root ──────────────────────────────────────────────────────────
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"

# ── Temporary workspace ───────────────────────────────────────────────────────
WORKDIR="$(mktemp -d /tmp/tier2_bundle_XXXXXX)"
ASSET_DIR="${WORKDIR}/asset-output"
SKEL_DIR="${WORKDIR}/skeleton"
ZIP_PATH="${WORKDIR}/tier2_bundle_size_check.zip"
mkdir -p "${ASSET_DIR}" "${SKEL_DIR}"

cleanup() {
    log "Cleaning up ${WORKDIR}"
    rm -rf "${WORKDIR}"
}
trap cleanup EXIT

# ── Read the current pinned versions from requirements.txt ───────────────────
REQUIREMENTS="${REPO_ROOT}/requirements.txt"
if [[ ! -f "${REQUIREMENTS}" ]]; then
    err "requirements.txt not found at ${REQUIREMENTS}"
    exit 2
fi

# Extract the exact pins we care about.
# strands-agents is pinned with ==; boto3 uses >= (range); pydantic uses ==.
STRANDS_PIN=$(grep -E '^strands-agents==' "${REQUIREMENTS}" | head -1 | tr -d '[:space:]')
BOTO3_PIN=$(grep -E '^boto3' "${REQUIREMENTS}" | head -1 | tr -d '[:space:]')
PYDANTIC_PIN=$(grep -E '^pydantic==' "${REQUIREMENTS}" | head -1 | tr -d '[:space:]')

log "Resolved pins from requirements.txt:"
log "  strands-agents : ${STRANDS_PIN}"
log "  boto3          : ${BOTO3_PIN}"
log "  pydantic       : ${PYDANTIC_PIN}"

if [[ -z "${STRANDS_PIN}" || -z "${BOTO3_PIN}" || -z "${PYDANTIC_PIN}" ]]; then
    err "Could not resolve one or more required pins from ${REQUIREMENTS}"
    exit 2
fi

# ── Write a minimal requirements file: dependency wall only ──────────────────
TIER2_REQS="${WORKDIR}/requirements-tier2-measure.txt"
cat > "${TIER2_REQS}" <<EOF
# Auto-generated by measure_tier2_bundle.sh — DO NOT commit.
# Dependency wall only: strands-agents + boto3 + pydantic.
# Versions taken verbatim from requirements.txt at run time.
${STRANDS_PIN}
${BOTO3_PIN}
${PYDANTIC_PIN}
EOF

log "Dependency wall requirements written to ${TIER2_REQS}"

# ── Verify Python is available ────────────────────────────────────────────────
if ! command -v python3 >/dev/null 2>&1; then
    err "python3 not found in PATH"
    exit 2
fi
PYTHON_VER="$(python3 --version 2>&1)"
log "Python: ${PYTHON_VER}"

# ── pip install into asset-output ────────────────────────────────────────────
# We install with --no-cache-dir and without --platform so this works on the
# host machine (macOS or Linux). The point is to measure total installed size,
# not to produce a production-deployable binary — for production bundling the
# CDK block uses --platform manylinux2014_x86_64 --only-binary=:all:.
log "Installing dependency wall into ${ASSET_DIR} ..."
# Install with --platform manylinux2014_x86_64 --python-version 3.12 to target
# the actual Lambda execution environment (Linux/x86_64, Python 3.12). This also
# avoids native compilation failures for packages like watchdog that require a
# C compiler on the host machine (macOS or Linux ARM). The Lambda runtime is
# Runtime.PYTHON_3_12 per infrastructure/lib/vsa-tier2-stack.ts:502.
python3 -m pip install \
    -r "${TIER2_REQS}" \
    -t "${ASSET_DIR}" \
    --platform manylinux2014_x86_64 \
    --python-version 3.12 \
    --implementation cp \
    --only-binary=:all: \
    --no-cache-dir \
    --quiet \
    2>&1 | tail -5 || { err "pip install failed (check that all packages have manylinux wheels for Python 3.12)"; exit 2; }

ok "pip install complete"

# ── Write a minimal Agent 2 module skeleton ───────────────────────────────────
# Per task constraints: dependency wall + agent module skeleton, NOT full app.
SKEL_AGENT_DIR="${ASSET_DIR}/agents/tier2"
mkdir -p "${SKEL_AGENT_DIR}"
cat > "${SKEL_AGENT_DIR}/__init__.py" <<'PYEOF'
# measure_tier2_bundle.sh minimal skeleton — agents/tier2/__init__.py
# This stub exercises the same import surface as the real module without
# pulling in the full application code path.
PYEOF

cat > "${SKEL_AGENT_DIR}/runner_skel.py" <<'PYEOF'
# measure_tier2_bundle.sh minimal skeleton — agents/tier2/runner_skel.py
# Mirrors the real import surface for bundle-size purposes only.
from __future__ import annotations
import boto3          # noqa: F401  — side-effect: includes botocore in bundle
import pydantic       # noqa: F401

try:
    import strands     # noqa: F401
except ImportError:
    pass
PYEOF

# ── Zip the bundle ────────────────────────────────────────────────────────────
log "Zipping bundle ..."
(cd "${ASSET_DIR}" && zip -r -q "${ZIP_PATH}" .)
ok "Zip complete: ${ZIP_PATH}"

# ── Measure sizes ─────────────────────────────────────────────────────────────
# stat: macOS uses -f%z, Linux uses --format='%s'
ZIP_BYTES=$(stat -f%z "${ZIP_PATH}" 2>/dev/null || stat --format='%s' "${ZIP_PATH}" 2>/dev/null)
# du -sb is Linux-only; macOS uses 512-byte blocks so multiply by 512
UNZIPPED_BYTES=$(du -sb "${ASSET_DIR}" 2>/dev/null | cut -f1 || du -s "${ASSET_DIR}" 2>/dev/null | awk '{print $1 * 512}')

ZIP_MB=$(echo "scale=1; ${ZIP_BYTES} / 1048576" | bc)
UNZIPPED_MB=$(echo "scale=1; ${UNZIPPED_BYTES} / 1048576" | bc)

# ── R1 gate evaluation ────────────────────────────────────────────────────────
GATE_MB=200
LIMIT_MB=250

log "============================================================"
log "BUNDLE SIZE MEASUREMENT RESULTS"
log "============================================================"
log "  Dependency wall pins:"
log "    ${STRANDS_PIN}"
log "    ${BOTO3_PIN}"
log "    ${PYDANTIC_PIN}"
log "------------------------------------------------------------"
log "  Zip size     : ${ZIP_MB} MB  (${ZIP_BYTES} bytes)"
log "  Unzipped size: ${UNZIPPED_MB} MB  (${UNZIPPED_BYTES} bytes)"
log "  R1 gate      : < ${GATE_MB} MB unzipped  (Lambda hard limit: ${LIMIT_MB} MB)"
log "============================================================"

UNZIPPED_INT=${UNZIPPED_BYTES}
GATE_BYTES=$(echo "${GATE_MB} * 1048576" | bc | cut -d. -f1)

if (( UNZIPPED_INT < GATE_BYTES )); then
    ok "R1 gate: CLEAR — ${UNZIPPED_MB} MB < ${GATE_MB} MB"
    echo ""
    echo "ZIP_MB=${ZIP_MB}"
    echo "UNZIPPED_MB=${UNZIPPED_MB}"
    echo "STRANDS_PIN=${STRANDS_PIN}"
    echo "BOTO3_PIN=${BOTO3_PIN}"
    echo "PYDANTIC_PIN=${PYDANTIC_PIN}"
    echo "R1_GATE=CLEAR"
    exit 0
else
    err "R1 gate: FIRES — ${UNZIPPED_MB} MB >= ${GATE_MB} MB"
    err "Per spec.md R1: evaluate Lambda layers or Fargate before Group 2 opens."
    err "Do NOT proceed to Group 2 until R1 is resolved."
    echo ""
    echo "ZIP_MB=${ZIP_MB}"
    echo "UNZIPPED_MB=${UNZIPPED_MB}"
    echo "STRANDS_PIN=${STRANDS_PIN}"
    echo "BOTO3_PIN=${BOTO3_PIN}"
    echo "PYDANTIC_PIN=${PYDANTIC_PIN}"
    echo "R1_GATE=FIRES"
    exit 1
fi
